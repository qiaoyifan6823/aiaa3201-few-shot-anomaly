"""Regenerate RESULTS.md and the AUROC-vs-shot figure from results/*.json.

    python make_results.py
    python make_results.py --methods part1_template_min part1_template_best part2_patchnn

Everything in the report tables comes from this script, so the numbers in the
text, the slides and the JSON files can never drift apart.
"""

from __future__ import annotations

import argparse
import glob
import json
import os
from collections import defaultdict

import numpy as np

from common import summarize

LABELS = {
    "part1_template_min": "Part 1 · min over refs (v1)",
    "part1_template_best": "Part 1 · closest template",
    "part1_template_median": "Part 1 · median template",
    "part2_patchnn": "Part 2 · patch-NN (ours)",
    "part2_official": "Part 2 · AnomalyDINO (official)",
}
CAT_ORDER = ["candle", "capsules", "cashew", "chewinggum", "fryum", "pipe_fryum"]


def label(method: str) -> str:
    return LABELS.get(method, method)


def load_rows(out_dir: str, methods):
    rows = []
    for m in methods:
        for f in sorted(glob.glob(os.path.join(out_dir, m, "*.json"))):
            r = json.load(open(f, encoding="utf-8"))
            r["method"] = m
            rows.append(r)
    return rows


def per_cat(rows, method, shot, key):
    acc = defaultdict(list)
    for r in rows:
        if r["method"] == method and r["shot"] == shot:
            acc[r["category"]].append(r.get(key, np.nan))
    return {c: float(np.nanmean(v)) for c, v in acc.items()}


def fmt(mean, std, scaled=100.0):
    return f"{scaled * mean:.1f} ± {scaled * std:.1f}"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default="results")
    ap.add_argument("--methods", nargs="+",
                    default=["part1_template_min", "part1_template_best",
                             "part1_template_median", "part2_patchnn"])
    ap.add_argument("--md", default="RESULTS.md")
    ap.add_argument("--fig", default="figures/auroc_vs_shot.png")
    args = ap.parse_args()

    rows = load_rows(args.out, args.methods)
    if not rows:
        raise SystemExit("no results found")
    summ = {m: summarize(args.out, m) for m in args.methods}
    shots = sorted({s for m in summ.values() for s in m})

    L = ["# Results — 6-category VisA few-shot anomaly detection\n",
         "Protocol: 1-class split, 6 categories, 1/2/4/8 references, seeds 0/1/2, "
         "DINOv2 ViT-S/14 @448 for Part 2, OK/NG threshold = 95th percentile of 20 held-out "
         "normal images, pixel AUROC computed at 448x448 including normal images with all-zero masks.\n",
         "*Generated by `make_results.py` — do not edit by hand.*\n"]

    for key, name in (("image_auroc", "Image AUROC (%)"), ("pixel_auroc", "Pixel AUROC (%)")):
        L.append(f"## {name}\n")
        L.append("| shot | " + " | ".join(label(m) for m in args.methods) + " |")
        L.append("|---|" + "---|" * len(args.methods))
        for s in shots:
            cells = []
            for m in args.methods:
                entry = summ[m].get(s)
                cells.append(fmt(entry[f"{key}_mean"], entry[f"{key}_std"]) if entry else "–")
            L.append(f"| {s}-shot | " + " | ".join(cells) + " |")
        L.append("")

    # per-category tables, one per shot value
    for s in shots:
        L.append(f"## Per-category image AUROC (%) — {s}-shot\n")
        L.append("| category | " + " | ".join(label(m) for m in args.methods) + " |")
        L.append("|---|" + "---|" * len(args.methods))
        for c in CAT_ORDER:
            cells = []
            for m in args.methods:
                v = per_cat(rows, m, s, "image_auroc").get(c)
                cells.append(f"{100 * v:.1f}" if v is not None else "–")
            L.append(f"| {c} | " + " | ".join(cells) + " |")
        L.append("")

    # threshold behaviour of the Part 1 variants
    p1 = [m for m in args.methods if m.startswith("part1")]
    if p1:
        L.append("## Part 1 at the calibrated OK/NG threshold (6-category mean)\n")
        L.append("| method | shot | FPR | FNR |")
        L.append("|---|---|---|---|")
        for m in p1:
            for s in shots:
                f = [r for r in rows if r["method"] == m and r["shot"] == s
                     and "fpr_at_threshold" in r]
                if not f:
                    continue
                L.append(f"| {label(m)} | {s} | "
                         f"{100 * np.mean([r['fpr_at_threshold'] for r in f]):.1f}% | "
                         f"{100 * np.mean([r['fnr_at_threshold'] for r in f]):.1f}% |")
        L.append("")

    with open(args.md, "w", encoding="utf-8") as fh:
        fh.write("\n".join(L) + "\n")
    print(f"wrote {args.md}")

    # ---------------------------------------------------------------- figure
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("matplotlib not available, skipping figure")
        return

    fig, axes = plt.subplots(1, 2, figsize=(9.6, 3.8))
    colors = ["#9AA5B1", "#3F6BA8", "#C07616", "#2E7D32", "#7B4EA3"]
    marks = ["o", "s", "^", "D", "v"]
    for ax, key, title in ((axes[0], "image_auroc", "Image AUROC"),
                           (axes[1], "pixel_auroc", "Pixel AUROC")):
        for i, m in enumerate(args.methods):
            xs = [s for s in shots if s in summ[m]]
            ys = [100 * summ[m][s][f"{key}_mean"] for s in xs]
            es = [100 * summ[m][s][f"{key}_std"] for s in xs]
            ax.errorbar(xs, ys, yerr=es, marker=marks[i % len(marks)], color=colors[i % len(colors)],
                        capsize=3, linewidth=1.8, markersize=5, label=label(m))
        ax.set_xlabel("references (shots)")
        ax.set_ylabel(f"{title} (%)")
        ax.set_xticks(shots)
        ax.grid(alpha=0.25, linewidth=0.6)
        ax.set_title(title, fontsize=11)
    axes[0].legend(fontsize=7.6, frameon=False, loc="lower right")
    fig.tight_layout()
    os.makedirs(os.path.dirname(args.fig) or ".", exist_ok=True)
    fig.savefig(args.fig, dpi=300, facecolor="white")
    print(f"wrote {args.fig}")


if __name__ == "__main__":
    main()
